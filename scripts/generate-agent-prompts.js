#!/usr/bin/env node

/**
 * generate-agent-prompts.js
 *
 * Generates agent-prompt.txt files for email-driven workflows from:
 *   - shared/agent-prompt-template.md (base structure)
 *   - shared/agent-config/<workflow>.json (per-workflow configuration)
 *   - shared/agent-capabilities/<name>.md (reusable capability fragments)
 *   - shared/agent-step3/<workflow>.md (workflow-specific decision logic)
 *
 * Usage:
 *   node scripts/generate-agent-prompts.js           # preview all
 *   node scripts/generate-agent-prompts.js --apply   # write all
 *   node scripts/generate-agent-prompts.js vq-loading          # preview one
 *   node scripts/generate-agent-prompts.js vq-loading --apply  # write one
 *
 * The generated prompts include a header warning not to edit directly.
 */

const fs = require('fs');
const path = require('path');

const BASE_DIR = path.resolve(__dirname, '..');
const SHARED_DIR = path.join(BASE_DIR, 'shared');
const CONFIG_DIR = path.join(SHARED_DIR, 'agent-config');
const CAPABILITIES_DIR = path.join(SHARED_DIR, 'agent-capabilities');
const STEP3_DIR = path.join(SHARED_DIR, 'agent-step3');

const GENERATED_HEADER = `# ═══════════════════════════════════════════════════════════════════════════════
# DO NOT EDIT THIS FILE DIRECTLY
#
# This agent-prompt.txt is generated from templates by:
#   node scripts/generate-agent-prompts.js --apply
#
# To modify:
#   1. Edit shared/agent-prompt-template.md for common structure
#   2. Edit shared/agent-capabilities/*.md for reusable capabilities
#   3. Edit shared/agent-step3/<workflow>.md for workflow-specific logic
#   4. Edit shared/agent-config/<workflow>.json for configuration
#   5. Run the generator
#
# Generated: {{TIMESTAMP}}
# ═══════════════════════════════════════════════════════════════════════════════

`;

/**
 * Load all workflow configs
 */
function loadConfigs() {
  const configs = {};
  const files = fs.readdirSync(CONFIG_DIR).filter(f => f.endsWith('.json'));

  for (const file of files) {
    const name = path.basename(file, '.json');
    const content = fs.readFileSync(path.join(CONFIG_DIR, file), 'utf8');
    configs[name] = JSON.parse(content);
  }

  return configs;
}

/**
 * Load a capability fragment and apply config substitutions
 */
function loadCapability(name, config) {
  const capPath = path.join(CAPABILITIES_DIR, `${name}.md`);
  if (!fs.existsSync(capPath)) {
    console.warn(`  Warning: capability file not found: ${capPath}`);
    return '';
  }

  let content = fs.readFileSync(capPath, 'utf8');

  // Remove the comment header (lines starting with #)
  content = content.replace(/^#[^\n]*\n/gm, '').trim();

  // Apply capability-specific config
  const capConfig = config.capabilityConfig?.[name] || {};

  // Also include top-level config values
  const allConfig = { ...config, ...capConfig };

  // Replace placeholders
  content = applyPlaceholders(content, allConfig);

  return content;
}

/**
 * Apply placeholder substitutions
 */
function applyPlaceholders(text, config) {
  // Simple {{KEY}} replacement
  text = text.replace(/\{\{(\w+)\}\}/g, (match, key) => {
    if (config[key] !== undefined) {
      return config[key];
    }
    return match; // Leave unreplaced if not found
  });

  // Conditional blocks: {{#if KEY}}...{{/if}}
  text = text.replace(/\{\{#if (\w+)\}\}([\s\S]*?)\{\{\/if\}\}/g, (match, key, content) => {
    const value = config[key];
    if (value && value !== false && value !== 'false') {
      return content;
    }
    return '';
  });

  // Array iteration: {{#each KEY}}...{{/each}}
  text = text.replace(/\{\{#each (\w+)\}\}([\s\S]*?)\{\{\/each\}\}/g, (match, key, content) => {
    const arr = config[key];
    if (!Array.isArray(arr)) return '';
    return arr.map(item => {
      if (typeof item === 'string') {
        return content.replace(/\{\{this\}\}/g, item);
      }
      return content;
    }).join('');
  });

  return text;
}

/**
 * Load STEP 3 content for a workflow
 */
function loadStep3(workflowKey) {
  const step3Path = path.join(STEP3_DIR, `${workflowKey}.md`);
  if (!fs.existsSync(step3Path)) {
    console.warn(`  Warning: STEP 3 file not found: ${step3Path}`);
    return '';
  }

  let content = fs.readFileSync(step3Path, 'utf8');

  // Remove comment header
  content = content.replace(/^#[^\n]*\n/gm, '').trim();

  return content;
}

/**
 * Generate a single agent prompt
 */
function generatePrompt(workflowKey, config) {
  const lines = [];

  // Opening line
  lines.push(`You are processing the ${config.inboxEmail} inbox on ${config.scheduleDesc}.`);
  lines.push('');

  // Intro text if present
  if (config.introText) {
    lines.push(config.introText);
    lines.push('');
  }

  // STEP 0
  if (config.decorators) {
    lines.push('═══════════════════════════════════════════════════════════════════════════════');
  }
  lines.push('STEP 0 — Read the universal operating philosophy.');
  if (config.decorators) {
    lines.push('═══════════════════════════════════════════════════════════════════════════════');
  }
  lines.push('');
  lines.push('Before STEP 1, Read `/home/analytics_user/workspace/astute-workinstructions/shared/agent-philosophy.md`. It covers the cross-workflow rules for: (a) the Jake test before escalating, (b) bias toward action, (c) using the investigation sub-Agent before clarify/needs_review, (d) MFR-resolver sanity check, (e) escalation hierarchy, (f) "loading is data capture" — vendor restrictions are an approval-flow concern, not a load-layer concern.');
  lines.push('');
  lines.push('The philosophy applies to every agent invocation. The workflow-specific .md (STEP 1) covers what THIS workflow does; the philosophy covers HOW every agent should think.');
  lines.push('');

  // STEP 1
  if (config.docPath) {
    if (config.decorators) {
      lines.push('═══════════════════════════════════════════════════════════════════════════════');
    }
    lines.push('STEP 1 — Read the contract.');
    if (config.decorators) {
      lines.push('═══════════════════════════════════════════════════════════════════════════════');
    }
    lines.push('');
    lines.push(`Use the Read tool on ${config.docPath} and read the section "${config.docSection}". The .md is the source of truth — do NOT work from prior-session memory or training data. Read it fresh${config.docExtraInstructions ? ` — ${config.docExtraInstructions}` : ''}.`);
    lines.push('');

    // Sections to know
    if (config.sectionsToKnow && config.sectionsToKnow.length > 0) {
      lines.push('Sections you must know cold:');
      for (const section of config.sectionsToKnow) {
        lines.push(`  - ${section}`);
      }
      lines.push('');
    }
  }

  // STEP 2
  if (config.decorators) {
    lines.push('═══════════════════════════════════════════════════════════════════════════════');
  }
  lines.push('STEP 2 — List unseen messages.');
  if (config.decorators) {
    lines.push('═══════════════════════════════════════════════════════════════════════════════');
  }
  lines.push('');
  lines.push('Run:');
  lines.push(`  node /home/analytics_user/workspace/astute-workinstructions/shared/email-workflow-poller.js list --workflow ${config.workflowKey}`);
  lines.push('');
  lines.push(`If 0 unseen messages, print "${config.summaryPrefix} SUMMARY: no unseen messages" and exit.`);
  lines.push('');

  // STEP 3
  if (config.decorators) {
    lines.push('═══════════════════════════════════════════════════════════════════════════════');
  }
  lines.push(`STEP 3 — ${config.step3Title || 'Process each message'}.`);
  if (config.decorators) {
    lines.push('═══════════════════════════════════════════════════════════════════════════════');
  }
  lines.push('');

  // Load STEP 3 content
  const step3Content = loadStep3(config.workflowKey);
  if (step3Content) {
    lines.push(step3Content);
    lines.push('');
  }

  // Transient error handling
  if (config.transientErrorExamples) {
    lines.push(`If a single message hits a transient error (${config.transientErrorExamples}), log the error in your output and continue with the next message. Do not abort the batch on per-message failure.`);
    lines.push('');
  }

  // Rate limiting (if specified in capabilities)
  if (config.capabilities?.includes('rate-limiting')) {
    const rateLimitAction = config.capabilityConfig?.['rate-limiting']?.RATE_LIMIT_ACTION || 'load_action';
    lines.push(`**Rate-limited deferral handling:** When \`${rateLimitAction}\` returns \`{ rateLimited: true, ... }\`:`);
    lines.push('- If `alreadyDeferred: false` → first deferral. Send ONE notification to Jake explaining budget exhaustion. The email stays UNSEEN for auto-retry.');
    lines.push('- If `alreadyDeferred: true` → repeat deferral (budget still exhausted). Do NOT notify again. Exit silently — email remains UNSEEN for retry on next tick when budget resets.');
    lines.push('');
  }

  // STEP 4
  if (config.decorators) {
    lines.push('═══════════════════════════════════════════════════════════════════════════════');
  }
  lines.push('STEP 4 — Summary.');
  if (config.decorators) {
    lines.push('═══════════════════════════════════════════════════════════════════════════════');
  }
  lines.push('');
  lines.push('At the end, print a single-line summary in this exact shape:');
  lines.push(`  ${config.summaryPrefix} SUMMARY: ${config.summaryCounters}`);
  lines.push('');
  lines.push(`If 0 unseen messages, print "${config.summaryPrefix} SUMMARY: no unseen messages" and exit.`);
  lines.push('');
  lines.push('NEVER include --dry-run on any route call. This is the production schedule.');
  lines.push('');

  // Known limitations
  if (config.knownLimitations && config.knownLimitations.length > 0) {
    if (config.decorators) {
      lines.push('═══════════════════════════════════════════════════════════════════════════════');
    }
    lines.push('KNOWN LIMITATIONS (flag these in summary if hit; deferred to a follow-up).');
    if (config.decorators) {
      lines.push('═══════════════════════════════════════════════════════════════════════════════');
    }
    lines.push('');
    for (const limitation of config.knownLimitations) {
      lines.push(`  - ${limitation}`);
      lines.push('');
    }
  }

  // Notification policy
  if (config.notificationPolicy) {
    lines.push('NOTIFICATION POLICY (CRITICAL):');
    lines.push(config.notificationPolicy);
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Generate the full prompt with header
 */
function generateFullPrompt(workflowKey, config) {
  const header = GENERATED_HEADER.replace('{{TIMESTAMP}}', new Date().toISOString());
  const body = generatePrompt(workflowKey, config);
  return header + body;
}

/**
 * Main execution
 */
function main() {
  const args = process.argv.slice(2);
  const applyMode = args.includes('--apply');
  const targetWorkflow = args.find(a => !a.startsWith('--'));

  console.log('Agent Prompt Generator');
  console.log('======================');
  console.log(`Mode: ${applyMode ? 'APPLY (will write files)' : 'PREVIEW (dry-run)'}`);
  console.log('');

  const configs = loadConfigs();
  const workflowsToProcess = targetWorkflow
    ? [targetWorkflow]
    : Object.keys(configs);

  const results = {
    success: [],
    skipped: [],
    failed: [],
  };

  for (const workflowKey of workflowsToProcess) {
    const config = configs[workflowKey];
    if (!config) {
      console.log(`Workflow '${workflowKey}' not found in configs`);
      results.failed.push(workflowKey);
      continue;
    }

    console.log(`Processing: ${workflowKey}`);

    // Check if this workflow uses a custom template
    if (config.useCustomTemplate) {
      console.log(`  Skipped: uses custom template (${config.customTemplatePath})`);
      results.skipped.push(workflowKey);
      continue;
    }

    try {
      const prompt = generateFullPrompt(workflowKey, config);
      const outputPath = path.join(BASE_DIR, config.outputPath);

      if (applyMode) {
        // Ensure directory exists
        const dir = path.dirname(outputPath);
        if (!fs.existsSync(dir)) {
          fs.mkdirSync(dir, { recursive: true });
        }

        fs.writeFileSync(outputPath, prompt, 'utf8');
        console.log(`  Written: ${outputPath}`);
        console.log(`  Size: ${prompt.length} bytes, ${prompt.split('\n').length} lines`);
      } else {
        console.log(`  Would write: ${outputPath}`);
        console.log(`  Size: ${prompt.length} bytes, ${prompt.split('\n').length} lines`);
        console.log(`  Preview (first 500 chars):`);
        console.log('  ---');
        console.log(prompt.substring(0, 500).split('\n').map(l => '  ' + l).join('\n'));
        console.log('  ...');
      }

      results.success.push(workflowKey);
    } catch (err) {
      console.log(`  Error: ${err.message}`);
      results.failed.push(workflowKey);
    }

    console.log('');
  }

  // Summary
  console.log('Summary');
  console.log('-------');
  console.log(`Success: ${results.success.length} (${results.success.join(', ') || 'none'})`);
  console.log(`Skipped: ${results.skipped.length} (${results.skipped.join(', ') || 'none'})`);
  console.log(`Failed: ${results.failed.length} (${results.failed.join(', ') || 'none'})`);

  if (!applyMode && results.success.length > 0) {
    console.log('');
    console.log('Run with --apply to write files.');
  }

  process.exit(results.failed.length > 0 ? 1 : 0);
}

main();
