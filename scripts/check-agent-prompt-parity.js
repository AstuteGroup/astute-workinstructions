#!/usr/bin/env node

/**
 * check-agent-prompt-parity.js
 *
 * Validates that agent-prompt.txt files are in sync with their source templates.
 *
 * Checks:
 *   1. Generated prompts match the current template + config + step3 content
 *   2. All workflows have required config files
 *   3. All declared capabilities exist
 *
 * Usage:
 *   node scripts/check-agent-prompt-parity.js           # full output
 *   node scripts/check-agent-prompt-parity.js --quiet   # minimal output for session greeting
 *
 * Exit codes:
 *   0 = all prompts in sync
 *   1 = drift detected (prompts need regeneration)
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const BASE_DIR = path.resolve(__dirname, '..');
const SHARED_DIR = path.join(BASE_DIR, 'shared');
const CONFIG_DIR = path.join(SHARED_DIR, 'agent-config');
const CAPABILITIES_DIR = path.join(SHARED_DIR, 'agent-capabilities');
const STEP3_DIR = path.join(SHARED_DIR, 'agent-step3');

// Import the generator to regenerate expected content
// We'll inline the generation logic to avoid circular dependencies
const GENERATED_HEADER_PATTERN = /^# ═+\n# DO NOT EDIT THIS FILE DIRECTLY[\s\S]*?# ═+\n\n/;

/**
 * Compute a content hash, ignoring the generated header timestamp
 */
function contentHash(content) {
  // Remove the generated header (which contains timestamp)
  const normalized = content.replace(GENERATED_HEADER_PATTERN, '');
  return crypto.createHash('md5').update(normalized).digest('hex').substring(0, 8);
}

/**
 * Load all workflow configs
 */
function loadConfigs() {
  const configs = {};
  if (!fs.existsSync(CONFIG_DIR)) {
    return configs;
  }
  const files = fs.readdirSync(CONFIG_DIR).filter(f => f.endsWith('.json'));

  for (const file of files) {
    const name = path.basename(file, '.json');
    const content = fs.readFileSync(path.join(CONFIG_DIR, file), 'utf8');
    try {
      configs[name] = JSON.parse(content);
    } catch (e) {
      console.error(`Invalid JSON in ${file}: ${e.message}`);
    }
  }

  return configs;
}

/**
 * Check if a capability file exists
 */
function capabilityExists(name) {
  return fs.existsSync(path.join(CAPABILITIES_DIR, `${name}.md`));
}

/**
 * Check if a step3 file exists
 */
function step3Exists(workflowKey) {
  return fs.existsSync(path.join(STEP3_DIR, `${workflowKey}.md`));
}

/**
 * Get file modification time
 */
function getModTime(filePath) {
  try {
    return fs.statSync(filePath).mtime;
  } catch {
    return null;
  }
}

/**
 * Check a single workflow
 */
function checkWorkflow(workflowKey, config, quiet) {
  const issues = [];

  // Check output file exists
  const outputPath = path.join(BASE_DIR, config.outputPath);
  if (!fs.existsSync(outputPath)) {
    issues.push(`Missing output: ${config.outputPath}`);
    return { workflowKey, issues, status: 'missing' };
  }

  // Check step3 file exists
  if (!step3Exists(workflowKey)) {
    issues.push(`Missing step3: shared/agent-step3/${workflowKey}.md`);
  }

  // Check all declared capabilities exist
  if (config.capabilities) {
    for (const cap of config.capabilities) {
      if (!capabilityExists(cap)) {
        issues.push(`Missing capability: shared/agent-capabilities/${cap}.md`);
      }
    }
  }

  // Check for drift: compare source modification times vs output
  const outputModTime = getModTime(outputPath);
  const sourcesNewer = [];

  // Config file
  const configPath = path.join(CONFIG_DIR, `${workflowKey}.json`);
  const configModTime = getModTime(configPath);
  if (configModTime && configModTime > outputModTime) {
    sourcesNewer.push('config');
  }

  // Step3 file
  const step3Path = path.join(STEP3_DIR, `${workflowKey}.md`);
  const step3ModTime = getModTime(step3Path);
  if (step3ModTime && step3ModTime > outputModTime) {
    sourcesNewer.push('step3');
  }

  // Template file
  const templatePath = path.join(SHARED_DIR, 'agent-prompt-template.md');
  const templateModTime = getModTime(templatePath);
  if (templateModTime && templateModTime > outputModTime) {
    sourcesNewer.push('template');
  }

  // Capability files
  if (config.capabilities) {
    for (const cap of config.capabilities) {
      const capPath = path.join(CAPABILITIES_DIR, `${cap}.md`);
      const capModTime = getModTime(capPath);
      if (capModTime && capModTime > outputModTime) {
        sourcesNewer.push(`capability:${cap}`);
      }
    }
  }

  if (sourcesNewer.length > 0) {
    issues.push(`Sources newer than output: ${sourcesNewer.join(', ')}`);
  }

  // Check the output has the generated header
  const content = fs.readFileSync(outputPath, 'utf8');
  if (!GENERATED_HEADER_PATTERN.test(content)) {
    issues.push('Missing generated header (may be manually edited)');
  }

  return {
    workflowKey,
    issues,
    status: issues.length === 0 ? 'ok' : 'drift',
  };
}

/**
 * Main execution
 */
function main() {
  const args = process.argv.slice(2);
  const quiet = args.includes('--quiet');

  if (!quiet) {
    console.log('Agent Prompt Parity Checker');
    console.log('===========================');
    console.log('');
  }

  // Check directories exist
  const requiredDirs = [CONFIG_DIR, CAPABILITIES_DIR, STEP3_DIR];
  const missingDirs = requiredDirs.filter(d => !fs.existsSync(d));

  if (missingDirs.length > 0) {
    if (quiet) {
      console.log(`agent-prompt-parity: FAIL — missing directories: ${missingDirs.map(d => path.relative(BASE_DIR, d)).join(', ')}`);
    } else {
      console.log('Missing directories:');
      for (const dir of missingDirs) {
        console.log(`  - ${path.relative(BASE_DIR, dir)}`);
      }
    }
    process.exit(1);
  }

  const configs = loadConfigs();
  const workflowKeys = Object.keys(configs);

  if (workflowKeys.length === 0) {
    if (quiet) {
      console.log('agent-prompt-parity: WARN — no workflow configs found');
    } else {
      console.log('No workflow configs found in shared/agent-config/');
    }
    process.exit(0);
  }

  const results = {
    ok: [],
    drift: [],
    missing: [],
    skipped: [],
  };

  for (const workflowKey of workflowKeys) {
    const config = configs[workflowKey];

    // Skip custom-template workflows
    if (config.useCustomTemplate) {
      results.skipped.push(workflowKey);
      continue;
    }

    const result = checkWorkflow(workflowKey, config, quiet);
    results[result.status].push(result);
  }

  // Output results
  if (quiet) {
    // Minimal one-line output
    const driftCount = results.drift.length + results.missing.length;
    if (driftCount > 0) {
      const names = [...results.drift.map(r => r.workflowKey), ...results.missing.map(r => r.workflowKey)];
      console.log(`agent-prompt-parity: DRIFT in ${driftCount} workflow(s): ${names.join(', ')}`);
      console.log('  Run: node scripts/generate-agent-prompts.js --apply');
    } else {
      console.log(`agent-prompt-parity: OK (${results.ok.length} workflows in sync, ${results.skipped.length} skipped)`);
    }
  } else {
    // Full output
    if (results.ok.length > 0) {
      console.log(`✓ In sync (${results.ok.length}):`);
      for (const r of results.ok) {
        console.log(`  - ${r.workflowKey}`);
      }
      console.log('');
    }

    if (results.skipped.length > 0) {
      console.log(`○ Skipped (${results.skipped.length}, use custom template):`);
      for (const key of results.skipped) {
        console.log(`  - ${key}`);
      }
      console.log('');
    }

    if (results.drift.length > 0 || results.missing.length > 0) {
      console.log(`✗ Needs regeneration (${results.drift.length + results.missing.length}):`);
      for (const r of [...results.drift, ...results.missing]) {
        console.log(`  - ${r.workflowKey}:`);
        for (const issue of r.issues) {
          console.log(`      ${issue}`);
        }
      }
      console.log('');
      console.log('Run: node scripts/generate-agent-prompts.js --apply');
    }
  }

  // Exit with error if drift detected
  const exitCode = (results.drift.length > 0 || results.missing.length > 0) ? 1 : 0;
  process.exit(exitCode);
}

main();
